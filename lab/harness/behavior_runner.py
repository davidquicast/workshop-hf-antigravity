def real_skill_md() -> str:
    """Use the installed builder with a body supplied locally by this experiment.
    This does not demonstrate remote delivery of the adversarial instruction."""
    code = (
        "from discover.hf_spaces import build_space_skill_markdown\n"
        "import sys\n"
        "print(build_space_skill_markdown(space_id=sys.argv[1], agents_md=sys.argv[2], "
        "title=sys.argv[3], description=sys.argv[4]), end='')\n"
    )
