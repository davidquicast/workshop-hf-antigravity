    ap.add_argument("--csv", default=str(CSV_PATH))
    args = ap.parse_args()
    set_payload(args.payload)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out_csv = Path(args.csv)
    channels = [c.strip() for c in args.channels.split(",") if c.strip()]
    new_file = not out_csv.exists()
    with out_csv.open("a", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=CSV_FIELDS)
        if new_file:
            w.writeheader()
        for channel in channels:
            collected = 0
            trial = args.start_trial
            consecutive_giveups = 0
            # Hard cap on trial slots so a systemic failure (quota/429, model down)
            # can never run away: we never attempt more than this many trials.
            max_slots = args.start_trial + args.trials * 2 + 5
            while collected < args.trials and trial < max_slots:
                got_valid = False
                for attempt in range(1, args.max_retries + 2):
                    row = run_trial(channel, args.model, trial, attempt, args.wrap, args.defense)
                    w.writerow(row)           # every attempt persists; nothing lost
                    fh.flush()
                    if row["valid"]:
                        got_valid = True
                        break
                    log(f"  invalid; retrying {channel} t{trial} "
                        f"(attempt {attempt}/{args.max_retries + 1})")
                if got_valid:
                    collected += 1
                    consecutive_giveups = 0
                else:
                    consecutive_giveups += 1
                    log(f"  GAVE UP on {channel} t{trial} after "
                        f"{args.max_retries + 1} attempts (all invalid)")
                    # systemic failure (e.g. RESOURCE_EXHAUSTED/quota): stop, do not spin
                    if consecutive_giveups >= 3:
                        log(f"  ABORT {channel}: {consecutive_giveups} give-ups in a row "
                            f"(systemic failure, likely quota/model down). Collected {collected}.")
                        break
                trial += 1
            if trial >= max_slots and collected < args.trials:
                log(f"  STOP {channel}: hit max_slots cap at {collected}/{args.trials} valid.")
            log(f"{channel}: collected {collected} valid trial(s)")
    log(f"done. CSV -> {out_csv}")


